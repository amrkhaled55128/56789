function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function state() {
  return db.get('quiz', {});
}

function nextQuestion(excludeIdx = -1) {
  let idx = Math.floor(Math.random() * QUESTIONS.length);
  if (excludeIdx >= 0 && QUESTIONS.length > 1 && idx === excludeIdx) {
    idx = (idx + 1) % QUESTIONS.length;
  }
  const order = shuffle([0, 1, 2, 3]);
  return { q: idx, order, at: Date.now() };
}

function askButtons(st) {
  const question = QUESTIONS[st.q];
  const options = [question.a, ...question.wrong];
  return st.order.map((origIdx, shownPos) => ({
    label: options[origIdx],
    id: `.quiz ans-${st.q}-${shownPos}`,
  }));
}

export default {
  name: 'quiz',
  aliases: ['اسئلة', 'سؤال', 'كويز', 'تحدي_المعلومات'],
  description: 'تحدي معلومات عربي ضخم — أجب واجمع عملات ورتب نقاطك',
  usage: '.quiz',
  async execute(sock, m, args) {
    const all = state();
    const meKey = m.identityKey ?? m.sender;

    // رد على اختيار
    const ansMatch = /^(?:ans-)?(\d+)-([0-3])$/.exec(args[0] ?? '');
    if (ansMatch) {
      const qIdx = Number(ansMatch[1]);
      const shownPos = Number(ansMatch[2]);
      const current = all[m.jid];

      if (!current || current.q !== qIdx) {
        return m.reply('⌛ السؤال ده انتهى أو اتغير — اضغط زر *سؤال جديد*');
      }

      const question = QUESTIONS[qIdx];
      const options = [question.a, ...question.wrong];
      const chosen = options[current.order[shownPos]];
      const correct = chosen === question.a;

      const stats = db.get('quizStats', {});
      const me = stats[meKey] ?? { score: 0, played: 0 };
      me.played++;

      let text;
      if (correct) {
        me.score++;
        const coins = addCoins(meKey, 15);
        text = `✅ *إجابة ممتازة وصحيحة!* 🎉\n"${question.a}"\n💰 +15 عملة (رصيدك الحالي: ${coins})\n📊 رصيدك من الأسئلة: *${me.score}* من ${me.played}`;
      } else {
        text = `❌ *للأسف إجابة خاطئة!* اخترت "${chosen}"\n✔️ الإجابة الصحيحة هي: *${question.a}*\n📊 رصيدك: ${me.score} من ${me.played} سؤال`;
      }
      stats[meKey] = me;

      all[m.jid] = nextQuestion(qIdx);
      db.set('quiz', all);
      db.set('quizStats', stats);

      await m.reply(text);
      return sendQuickReplies(sock, m.jid, {
        title: '🧠 السؤال التالي',
        text: `${QUESTIONS[all[m.jid].q].q}\n\nاختر الإجابة الصحيحة 👇`,
        buttons: askButtons(all[m.jid]),
      });
    }

    // بدء / متابعة سؤال جديد
    if (!all[m.jid]) {
      all[m.jid] = nextQuestion();
      db.set('quiz', all);
    }
    const st = all[m.jid];
    const stats = db.get('quizStats', {});
    const me = stats[meKey] ?? { score: 0, played: 0 };

    return sendQuickReplies(sock, m.jid, {
      title: `🧠 تحدي المعلومات — نقاطك: ${me.score}`,
      text: `${QUESTIONS[st.q].q}\n\nاختر الإجابة الصحيحة من الأزرار 👇`,
      buttons: askButtons(st),
    });
  },
};
